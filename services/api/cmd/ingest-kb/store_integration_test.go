// fixedEmbedder returns a constant, correctly-shaped vector.
//
// Constant rather than content-derived: this file is about the database,
// and `ingest_test.go` already asserts that each chunk gets the vector for
// its own text. A known first component (0.5) makes the round-trip
// assertion above exact.
type fixedEmbedder struct {
	model string

	// width overrides the vector width, for the rejection test.
	width int

	// wrongWidthAt makes exactly one vector the wrong width, counted
	// across the whole run, so a failure lands mid-document.
	wrongWidthAt int

	seen int
}

func (e *fixedEmbedder) Embed(_ context.Context, texts []string) ([][]float32, string, error) {
	width := e.width
	if width == 0 {
		width = embeddingWidth
	}

	vectors := make([][]float32, len(texts))
	for index := range texts {
		this := width
		if e.wrongWidthAt > 0 && e.seen+index == e.wrongWidthAt {
			this = width - 1
		}
		vector := make([]float32, this)
		if this > 0 {
			vector[0] = 0.5
		}
		for component := 1; component < this; component++ {
			vector[component] = float32(component) / float32(this)
		}
		vectors[index] = vector
	}

	e.seen += len(texts)
	return vectors, e.model, nil
}

func loadTestCorpus(t *testing.T) []knowledge.ChunkedDocument {
	t.Helper()

	corpus, err := loadCorpus(
		filepath.Join("..", "..", "internal", "knowledge", "testdata", "corpus"),
		knowledge.DefaultChunkConfig())
	if err != nil {
		t.Fatalf("load fixtures: %v", err)
	}

	documents := make([]knowledge.ChunkedDocument, 0, len(corpus))
	for _, loaded := range corpus {
		documents = append(documents, knowledge.ChunkedDocument{
			Document: loaded.doc, Chunks: loaded.chunks,
		})
	}
	return documents
}

func syntheticDocument(title, body, checksum string) *knowledge.Document {
	return &knowledge.Document{
		Title:           title,
		Category:        "test",
		Source:          "editorial",
		Language:        "en",
		AstrologySystem: "vedic",
		Authority:       50,
		Version:         1,
		Body:            body,
		Metadata:        json.RawMessage(`{"topic":["testing"]}`),
		Checksum:        checksum,
		Path:            title + ".md",
	}
}

func jsonOfRaw(t *testing.T, raw json.RawMessage) map[string]any {
	t.Helper()
	var fields map[string]any
	if err := json.Unmarshal(raw, &fields); err != nil {
		t.Fatalf("metadata is not an object: %v", err)
	}
	return fields
}

// startStore brings up pgvector Postgres with every migration applied.
func startStore(ctx context.Context, t *testing.T) (
	store *pgStore, pool *pgxpool.Pool, readerDSN string, terminate func(),
) {
	t.Helper()

	initSQL, err := filepath.Abs(filepath.Join(
		"..", "..", "..", "..", "infrastructure", "docker", "init", "01-init.sql"))
	if err != nil {
		t.Fatalf("resolve init script: %v", err)
	}
	if _, err := os.Stat(initSQL); err != nil {
		t.Fatalf("bootstrap SQL not found at %s: %v", initSQL, err)
	}

	container, err := testcontainers.GenericContainer(ctx, testcontainers.GenericContainerRequest{
		ContainerRequest: testcontainers.ContainerRequest{
			// pgvector's image, not plain postgres: `vector(768)` needs the
			// extension and `01-init.sql` creates it.
			Image:        "pgvector/pgvector:pg16",
			ExposedPorts: []string{"5432/tcp"},
			Env: map[string]string{
				"POSTGRES_USER":     "astro",
				"POSTGRES_PASSWORD": "astro",
				"POSTGRES_DB":       "astro_dev",
			},
			Files: []testcontainers.ContainerFile{{
				HostFilePath:      initSQL,
				ContainerFilePath: "/docker-entrypoint-initdb.d/01-init.sql",
				FileMode:          0o644,
			}},
			WaitingFor: wait.ForLog("database system is ready to accept connections").
				WithOccurrence(2).
				WithStartupTimeout(90 * time.Second),
		},
		Started: true,
	})
	if err != nil {
		testsupport.ContainerUnavailable(t, "Postgres", err)
	}

	host, err := container.Host(ctx)
	if err != nil {
		t.Fatalf("container host: %v", err)
	}
	port, err := container.MappedPort(ctx, "5432/tcp")
	if err != nil {
		t.Fatalf("mapped port: %v", err)
	}

	dsn := func(user, pass string) string {
		return fmt.Sprintf("postgresql://%s:%s@%s:%s/astro_dev?sslmode=disable",
			user, pass, host, port.Port())
	}

	pool, err = pgxpool.New(ctx, dsn("astro", "astro"))
	if err != nil {
		t.Fatalf("pool: %v", err)
	}

	applyEveryMigration(ctx, t, pool)

	return newPGStore(pool), pool, dsn("astro_ro", "astro_ro"), func() {
		pool.Close()
		_ = container.Terminate(context.Background())
	}
}

// applyEveryMigration runs each *.up.sql in order, as the real deployment
// does. Reading the files rather than duplicating the schema means this
// test fails if a future migration forgets its grants.
func applyEveryMigration(ctx context.Context, t *testing.T, pool *pgxpool.Pool) {
	t.Helper()

	dir, err := filepath.Abs(filepath.Join("..", "..", "db", "migrations"))
	if err != nil {
		t.Fatalf("resolve migrations: %v", err)
	}

	files, err := filepath.Glob(filepath.Join(dir, "*.up.sql"))
	if err != nil {
		t.Fatalf("glob migrations: %v", err)
	}
	if len(files) == 0 {
		t.Fatalf("no migrations in %s", dir)
	}
	sort.Strings(files) // numeric prefixes make lexical order correct

	for _, file := range files {
		content, err := os.ReadFile(file)
		if err != nil {
			t.Fatalf("read %s: %v", file, err)
		}
		if _, err := pool.Exec(ctx, string(content)); err != nil {
			t.Fatalf("apply %s: %v", filepath.Base(file), err)
		}
	}
}
