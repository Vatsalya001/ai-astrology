/*
PHASE-05 task 5.4 against real Postgres.

`ingest_test.go` already covers the pipeline's logic with a fake store, and
deliberately: it is fast, runs in CI, and tests the branches. This file
tests the things a fake cannot reproduce, which are exactly the ones that
matter here:

  - the `::vector` cast actually accepting `FormatVector`'s output, and
    REJECTING a vector of the wrong width
  - `ON CONFLICT (title, language, version)` matching the real index
  - a real transaction rolling back a real partial write
  - the generated-column `tsv` populating itself from inserted content
  - `astro_ro` being able to read what the writer wrote, which is the whole
    point of the grants in migration 000007

`.claude/rules/testing.md`: "Do not mock the database. The bugs that matter
live in behaviour a mock cannot reproduce."

No model is called. The embedder here is deterministic and local, because
CI must never call a language model — but the DATABASE is real, because the
database is what this file is about.
*/

const embeddingWidth = 768

func TestTheFullPipelineWritesAnEmbeddedCorpus(t *testing.T) {
	ctx := context.Background()
	store, pool, readerDSN, terminate := startStore(ctx, t)
	defer terminate()

	corpus := loadTestCorpus(t)
	embedder := &fixedEmbedder{model: "nomic-embed-text"}

	report, err := knowledge.Ingest(ctx, corpus, embedder, store,
		knowledge.IngestOptions{BatchSize: 4})
	if err != nil {
		t.Fatalf("ingest: %v", err)
	}
	if report.Ingested != len(corpus) {
		t.Fatalf("ingested %d of %d", report.Ingested, len(corpus))
	}

	counts, err := store.Counts(ctx)
	if err != nil {
		t.Fatal(err)
	}
	if int(counts.Documents) != len(corpus) {
		t.Errorf("stored %d documents, chunked %d", counts.Documents, len(corpus))
	}
	if counts.Chunks == 0 {
		t.Fatal("no chunks were stored")
	}

	// The one that would be invisible from the application side. An
	// unembedded chunk still matches keyword search, so retrieval keeps
	// working and quietly loses half its ranking signal.
	if counts.Unembedded != 0 {
		t.Errorf("%d chunks have no embedding", counts.Unembedded)
	}
	if counts.EmbeddingModels != 1 {
		t.Errorf("the corpus holds vectors from %d models", counts.EmbeddingModels)
	}

	// The vector came back as a vector, at the right width, and with the
	// values that went in. `vector_dims` is pgvector's own function, so
	// this is Postgres confirming it parsed the text form rather than
	// storing a string that happened to be accepted.
	var dims int
	var first float32
	err = pool.QueryRow(ctx, `
		SELECT vector_dims(embedding), (embedding::real[])[1]
		FROM knowledge_chunks WHERE embedding IS NOT NULL LIMIT 1`).Scan(&dims, &first)
	if err != nil {
		t.Fatalf("read back a vector: %v", err)
	}
	if dims != embeddingWidth {
		t.Errorf("stored vector has %d dimensions, want %d", dims, embeddingWidth)
	}
	if first != 0.5 {
		t.Errorf("first component round-tripped as %v, want 0.5", first)
	}

	// The generated column. A trigger is the alternative and a trigger is
	// a thing to forget; this asserts the column is actually generated by
	// never having written it.
	var ranked int
	err = pool.QueryRow(ctx, `
		SELECT count(*) FROM knowledge_chunks
		WHERE tsv @@ plainto_tsquery('english', 'saturn')`).Scan(&ranked)
	if err != nil {
		t.Fatalf("keyword search: %v", err)
	}
	if ranked == 0 {
		t.Error("tsv matched nothing for 'saturn'; the generated column is not populating")
	}

	// `astro_ro` reading what the writer wrote. Migration 000007 grants
	// SELECT explicitly because `01-init.sql` ran before these tables
	// existed, and a missing grant surfaces as a permission error inside
	// retrieval at the first chat request.
	reader, err := pgx.Connect(ctx, readerDSN)
	if err != nil {
		t.Fatalf("connect as astro_ro: %v", err)
	}
	defer reader.Close(ctx)

	var readable int
	if err := reader.QueryRow(ctx,
		`SELECT count(*) FROM knowledge_chunks`).Scan(&readable); err != nil {
		t.Fatalf("astro_ro cannot read knowledge_chunks: %v", err)
	}
	if int64(readable) != counts.Chunks {
		t.Errorf("astro_ro sees %d chunks, writer wrote %d", readable, counts.Chunks)
	}

	// And still cannot write. The single-writer rule is enforced by
	// grants, and a test that only proves the read half would not notice
	// the day somebody grants INSERT to fix something.
	_, err = reader.Exec(ctx,
		`DELETE FROM knowledge_chunks WHERE chunk_index = 0`)
	if err == nil {
		t.Error("astro_ro deleted knowledge_chunks; the read-only grant is not holding")
	}
}

func TestAWrongWidthVectorIsRejectedByPostgres(t *testing.T) {
	// The reason the embedding crosses into Postgres as text and is cast
	// rather than being handed over as bytes: `::vector` validates the
	// width against the column. A width mismatch either fails here —
	// loud, fine — or lands in a column loose enough to accept it, after
	// which every similarity score in the product is meaningless and
	// nothing errors.
	ctx := context.Background()
	store, _, _, terminate := startStore(ctx, t)
	defer terminate()

	corpus := loadTestCorpus(t)[:1]

	for _, width := range []int{1, 767, 769} {
		t.Run(fmt.Sprintf("width-%d", width), func(t *testing.T) {
			_, err := knowledge.Ingest(ctx, corpus,
				&fixedEmbedder{model: "m", width: width}, store,
				knowledge.IngestOptions{BatchSize: 4, Force: true})
			if err == nil {
				t.Fatalf("a %d-dimension vector was accepted into vector(%d)",
					width, embeddingWidth)
			}
			if !strings.Contains(err.Error(), "dimension") &&
				!strings.Contains(err.Error(), "vector") {
				t.Errorf("error does not mention the vector: %v", err)
			}
		})
	}
}

func TestReIngestingIsIdempotentAgainstTheRealUniqueIndex(t *testing.T) {
	// §16: "Ingestion is deterministic and re-runnable without
	// duplicates". The fake store enforces identity with a Go map; this
	// asserts the real `ON CONFLICT` target matches the real
	// `kd_identity_idx`, which is the part that would fail as
	// "there is no unique or exclusion constraint matching the ON CONFLICT
	// specification" rather than as a duplicate.
	ctx := context.Background()
	store, _, _, terminate := startStore(ctx, t)
	defer terminate()

	corpus := loadTestCorpus(t)
	embedder := &fixedEmbedder{model: "m"}

	for run := 0; run < 3; run++ {
		opts := knowledge.IngestOptions{BatchSize: 4, Force: true}
		if _, err := knowledge.Ingest(ctx, corpus, embedder, store, opts); err != nil {
			t.Fatalf("run %d: %v", run, err)
		}
	}

	counts, err := store.Counts(ctx)
	if err != nil {
		t.Fatal(err)
	}
	if int(counts.Documents) != len(corpus) {
		t.Errorf("three runs produced %d documents for %d files",
			counts.Documents, len(corpus))
	}

	// Chunks too. The document upsert could be idempotent while chunk
	// inserts accumulated, which is what `DeleteKnowledgeChunks` before
	// every insert exists to prevent.
	expected := 0
	for _, document := range corpus {
		expected += len(document.Chunks)
	}
	if int(counts.Chunks) != expected {
		t.Errorf("three runs produced %d chunks for %d chunked", counts.Chunks, expected)
	}
}

func TestShrinkingADocumentLeavesNoOrphanChunks(t *testing.T) {
	// Against the real UNIQUE (document_id, chunk_index). Orphan chunks
	// would still match keyword search and still be retrieved — the only
	// chunks in the corpus whose text no authored file contains.
	ctx := context.Background()
	store, pool, _, terminate := startStore(ctx, t)
	defer terminate()

	long := syntheticDocument("Shrinking", strings.Repeat("A sentence that is here. ", 40), "sum-1")
	short := syntheticDocument("Shrinking", "One short sentence now.", "sum-2")
	cfg := knowledge.ChunkConfig{SizeTokens: 60, OverlapTokens: 10}

	for _, doc := range []*knowledge.Document{long, short} {
		chunks, err := knowledge.ChunkDocument(doc, cfg)
		if err != nil {
			t.Fatal(err)
		}
		_, err = knowledge.Ingest(ctx,
			[]knowledge.ChunkedDocument{{Document: doc, Chunks: chunks}},
			&fixedEmbedder{model: "m"}, store, knowledge.IngestOptions{BatchSize: 4})
		if err != nil {
			t.Fatal(err)
		}
	}

	var stored int
	var content string
	err := pool.QueryRow(ctx, `
		SELECT count(*), min(content) FROM knowledge_chunks`).Scan(&stored, &content)
	if err != nil {
		t.Fatal(err)
	}

	if stored != 1 {
		t.Errorf("%d chunks remain after shrinking the document to one", stored)
	}
	if !strings.Contains(content, "One short sentence now.") {
		t.Errorf("the surviving chunk is the old one: %q", content)
	}
}

func TestARealTransactionRollsBackAPartialDocument(t *testing.T) {
	// §4 requires documents and chunks to go in together. The fake store
	// models this with a snapshot; this asserts the real Postgres
	// transaction does it, which is the claim that actually ships.
	ctx := context.Background()
	store, pool, _, terminate := startStore(ctx, t)
	defer terminate()

	doc := syntheticDocument("Will Fail",
		strings.Repeat("A sentence that is here. ", 40), "sum-1")
	chunks, err := knowledge.ChunkDocument(doc,
		knowledge.ChunkConfig{SizeTokens: 60, OverlapTokens: 10})
	if err != nil {
		t.Fatal(err)
	}
	if len(chunks) < 3 {
		t.Fatalf("need several chunks, got %d", len(chunks))
	}

	// A vector of the wrong width on the LAST chunk only, so the document
	// and the earlier chunks are already written when the failure lands.
	embedder := &fixedEmbedder{model: "m", wrongWidthAt: len(chunks) - 1}

	_, err = knowledge.Ingest(ctx,
		[]knowledge.ChunkedDocument{{Document: doc, Chunks: chunks}},
		embedder, store, knowledge.IngestOptions{BatchSize: 64})
	if err == nil {
		t.Fatal("the bad vector was accepted")
	}

	var documents, storedChunks int
	if err := pool.QueryRow(ctx, `
		SELECT (SELECT count(*) FROM knowledge_documents),
		       (SELECT count(*) FROM knowledge_chunks)`).Scan(&documents, &storedChunks); err != nil {
		t.Fatal(err)
	}

	if documents != 0 || storedChunks != 0 {
		t.Errorf("after rollback: %d documents, %d chunks — both must be 0, "+
			"because a document visible without its chunks is one retrieval "+
			"cannot reach but the corpus count includes", documents, storedChunks)
	}
}

func TestStoredMetadataIsQueryableByTheRetrievalFilter(t *testing.T) {
	// The chunk metadata is only useful if `metadata @> $1` matches it —
	// which is how §4's retrieval SQL narrows before it ranks, through the
	// `jsonb_path_ops` GIN index. A chunker that wrote the right JSON into
	// the wrong shape would pass every unit test in this repo.
	ctx := context.Background()
	store, pool, _, terminate := startStore(ctx, t)
	defer terminate()

	corpus := loadTestCorpus(t)
	if _, err := knowledge.Ingest(ctx, corpus, &fixedEmbedder{model: "m"}, store,
		knowledge.IngestOptions{BatchSize: 4}); err != nil {
		t.Fatal(err)
	}

	// Taken from the corpus rather than hardcoded, so this test keeps
	// meaning if the fixture changes.
	wanted := jsonOfRaw(t, corpus[0].Chunks[0].Metadata)
	if len(wanted) == 0 {
		t.Skip("the first fixture chunk carries no metadata")
	}

	for key, value := range wanted {
		if _, isList := value.([]any); isList {
			// Containment against an array is a different predicate; the
			// retriever uses scalar keys.
			continue
		}

		filter, err := json.Marshal(map[string]any{key: value})
		if err != nil {
			t.Fatal(err)
		}

		var matches int
		if err := pool.QueryRow(ctx,
			`SELECT count(*) FROM knowledge_chunks WHERE metadata @> $1`,
			string(filter)).Scan(&matches); err != nil {
			t.Fatalf("containment query on %s: %v", filter, err)
		}
		if matches == 0 {
			t.Errorf("no chunk matches %s, but a chunk was stored with it", filter)
		}
	}
}

